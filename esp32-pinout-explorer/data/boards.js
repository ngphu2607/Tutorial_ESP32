function clonePin(base, overrides = {}) {
  return {
    ...base,
    ...overrides,
    specs: { ...base.specs, ...(overrides.specs || {}) },
    tags: overrides.tags || base.tags,
    categories: overrides.categories || base.categories,
    warnings: overrides.warnings || base.warnings,
    useCases: overrides.useCases || base.useCases,
  };
}

