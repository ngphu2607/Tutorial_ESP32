  silk,
  gpio,
  name,
  primaryType = 'safe',
  safety = 'safe',
  categories = ['safe', 'pwm'],
  tags = [],
  shortDesc,
  detailDesc,
  adc = 'Không',
  touch = 'Không',
  rtc = 'Không',
  comm = 'Linh hoạt qua GPIO Matrix (I2C, SPI, UART, I2S...)',
  bootState = 'Ổn định (An toàn)',
